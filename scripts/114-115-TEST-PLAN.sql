-- ═══════════════════════════════════════════════════════════════════════════
-- שלב 0 — צילום המצב הקיים.  להריץ ראשון. לשמור את הפלט של שתי השאילתות.
-- ═══════════════════════════════════════════════════════════════════════════

select policyname, cmd, permissive, roles, qual, with_check
from pg_policies
where schemaname = 'public'
  and tablename in ('system_admins', 'company_members')
order by tablename, policyname;

select grantee, privilege_type
from information_schema.role_table_grants
where table_schema = 'public'
  and table_name in ('system_admins', 'company_members')
order by table_name, grantee, privilege_type;

-- שמור את שתי הטבלאות האלה (צילום מסך או העתקה לקובץ) לפני שממשיכים.


-- ═══════════════════════════════════════════════════════════════════════════
-- שלב 1 — בדיקה שהחור באמת פתוח כרגע.  לפני התיקון.
-- ═══════════════════════════════════════════════════════════════════════════
-- המטרה: לראות במו עינייך שההכנסה מצליחה עכשיו. בלי זה, בדיקה שנכשלת אחרי
-- התיקון לא מוכיחה כלום — אולי היא נכשלה מסיבה אחרת לגמרי.
--
-- כל הבדיקות עטופות ב-begin; ... rollback;  ולכן שום דבר לא נשמר במסד,
-- גם כשההכנסה מצליחה. אפשר להריץ אותן בבטחה על פרודקשן.

-- ── 1.א  מאיפה להשיג את שני המזהים ─────────────────────────────────────────

-- שאילתה אחת שמחזירה את שני המזהים יחד. אין מה להדביק לתוכה.
-- כל שורה בתוצאה היא זוג תקין: משתמש, וחברה שאין לו איתה שום קשר.
-- בחר שורה אחת והשתמש בשני הערכים שלה בכל הבדיקות בהמשך.
select
  u.id    as test_user_id,
  u.email as test_user_email,
  fc.id   as foreign_company_id,
  fc.company_name as foreign_company_name
from auth.users u
cross join lateral (
  select c.id, c.company_name
  from public.companies c
  where c.auth_user_id is distinct from u.id
    and not exists (
      select 1 from public.company_members m
      where m.company_id = c.id
        and m.user_id = u.id
    )
  limit 1
) fc
order by u.created_at desc
limit 10;
-- אם התוצאה ריקה לגמרי — לכל משתמש יש קשר לכל החברות, ואי אפשר לבדוק כך.


-- ── 1.ב  לפני התיקון: הצטרפות לחברה זרה — אמורה להצליח ─────────────────────
begin;
set local role authenticated;
set local request.jwt.claims = '{"sub":"<UUID_של_משתמש_הבדיקה>","role":"authenticated"}';

insert into public.company_members (company_id, user_id, role)
values ('<UUID_של_חברה_זרה>'::uuid, '<UUID_של_משתמש_הבדיקה>'::uuid, 'owner');

rollback;

-- מה אמור לקרות:  INSERT 0 1  — כלומר הצליח.
-- זה החור. משתמש רשום צירף את עצמו לחברה של מישהו אחר.
-- ה-rollback ביטל את זה, לא נשמר כלום.


-- ── 1.ג  לפני התיקון: להפוך את עצמך לאדמין מערכת — אמורה להצליח ────────────
-- שים לב: system_admins.email הוא NOT NULL ו-UNIQUE, ולכן חייבים למלא אותו.
-- בלעדיו ההכנסה תיכשל בגלל העמודה החסרה ולא בגלל ההרשאות — וזו תהיה
-- בדיקה חסרת ערך שנראית כאילו עברה.
begin;
set local role authenticated;
set local request.jwt.claims = '{"sub":"<UUID_של_משתמש_הבדיקה>","role":"authenticated"}';

insert into public.system_admins (auth_user_id, email)
values ('<UUID_של_משתמש_הבדיקה>'::uuid, 'rls-test-delete-me@example.com');

rollback;

-- מה אמור לקרות:  INSERT 0 1  — כלומר הצליח.
-- זה החור השני. משתמש רשום הפך את עצמו לאדמין מערכת.


